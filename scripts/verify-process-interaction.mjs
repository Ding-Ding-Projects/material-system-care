import assert from 'node:assert/strict';
import {readFileSync, realpathSync} from 'node:fs';
import {resolve, relative, isAbsolute} from 'node:path';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';

const [rootArg, runArg, bundleArg] = process.argv.slice(2);
assert(rootArg && runArg && bundleArg, 'Expected repository, private run and bundle');
const root=realpathSync(rootArg), run=realpathSync(runArg), bundle=realpathSync(bundleArg);
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
const contained=(base,path)=>{const p=realpathSync(resolve(base,path)), rel=relative(base,p);assert(rel&&!rel.startsWith('..')&&!isAbsolute(rel));return p;};
const bytes=(base,path)=>readFileSync(contained(base,path));
const json=(base,path)=>JSON.parse(bytes(base,path).toString('utf8').replace(/^\uFEFF/,''));
const receipt=json(root,'docs/verification/process-inventory.json');
assert.equal(receipt.schemaVersion,1);
assert.equal(receipt.scope,'read-only-filtered-process-inventory');
assert.equal(receipt.publishedPixels,false);
const producer=json(run,'build-receipt.json'), manifest=json(bundle,'bundle-manifest.json');
assert.equal(receipt.sourceCommit,producer.source);
assert.equal(receipt.bundleSha256,producer.bundleSha256);
assert.equal(manifest.bundleSha256,producer.bundleSha256);
for(const entry of manifest.files){const b=bytes(bundle,entry.path);assert.equal(b.length,entry.bytes);assert.equal(hash(b),entry.sha256);}
execFileSync('git',['cat-file','-e',`${receipt.sourceCommit}^{commit}`],{cwd:root,windowsHide:true});
const frame=bytes(run,'output/processes-003.png');
assert.equal(hash(frame),receipt.captureSha256);
assert.equal(frame.readUInt32BE(16),receipt.width);assert.equal(frame.readUInt32BE(20),receipt.height);
for(const [path,key] of [['inputs.json','inputReceiptSha256'],['engine-identity.json','identityReceiptSha256'],['teardown.json','teardownReceiptSha256']])assert.equal(hash(bytes(run,path)),receipt[key]);
const launch=json(run,'launch.json'), children=json(run,'children.json'), inputs=json(run,'inputs.json');
assert(launch.created&&launch.process.pid===launch.pid);
assert.equal(realpathSync(launch.process.executablePath),contained(bundle,'material_system_care.exe'));
assert(children.ok&&children.client_ok&&children.parent_hwnd===launch.hwnd&&children.children.length===1);
const child=children.children[0];assert.equal(child.class,'FLUTTERVIEW');
assert.equal(inputs.length,28);
assert.equal(inputs[0].name,'mouse_click');assert.deepEqual([inputs[0].params.x,inputs[0].params.y],[250,230]);
assert(inputs.slice(1,26).every(i=>i.name==='type_text'&&i.params.text.length===1));
assert.equal(inputs.slice(1,26).map(i=>i.params.text).join(''),'MaterialSystemCare.Engine');
assert.equal(inputs[26].name,'mouse_click');assert.deepEqual([inputs[26].params.x,inputs[26].params.y],[800,560]);
assert.equal(inputs[27].name,'mouse_click');assert.deepEqual([inputs[27].params.x,inputs[27].params.y],[113,165]);
for(const i of inputs)assert(i.params.hwnd===child.handle&&i.result.ok&&i.result.client_ok&&i.result.mode==='background'&&i.result.target_hwnd===child.handle);
const identity=json(run,'engine-identity.json');
assert(identity.rowMatchesNativeStart&&identity.native.pid===identity.cim.pid&&identity.cim.parentPid===launch.pid);
assert.equal(realpathSync(identity.native.path),contained(bundle,'engine/MaterialSystemCare.Engine.exe'));
assert.equal(identity.native.path,identity.cim.path);
const teardown=json(run,'teardown.json');assert(teardown.processesAbsent&&teardown.desktopAndEngineExecutablesAbsent&&JSON.parse(teardown.result).closed);
assert(receipt.verified.filterTextVisuallyInspected&&receipt.verified.measuredEngineRowVisuallyInspected&&receipt.verified.rowMatchesNativeIdentity&&receipt.verified.closeControlDisabled&&receipt.verified.ownedTeardown);
assert.equal(receipt.verified.processCloseActionInvoked,false);assert.equal(receipt.verified.nativeCompositor,false);assert.equal(receipt.verified.fullInputMatrix,false);
console.log(`PASS process interaction: ${manifest.files.length} bundle files, single-character input receipts, private frame bytes, identity and teardown. Pixel inspection remains a separate assertion; no close or full-input proof.`);
